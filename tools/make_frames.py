"""Make the H.264 pictures the hub streams.

Writes the two built-in pictures to lib/sensorcam/cam_frames_data.cpp, and one file per state for
every sensor in sensors.json to data/<MAC>/<input>/, laid out for upload through the hub's web page
or with `pio run -t uploadfs`. Needs ffmpeg.
"""
import json, os, re, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILTIN = os.path.join(ROOT, 'lib', 'sensorcam', 'cam_frames_data.cpp')
SNAPSHOTS = os.path.join(ROOT, 'lib', 'sensorcam', 'cam_snapshots_data.cpp')
DATA = os.path.join(ROOT, 'data')
WIDTH, HEIGHT, FPS = 640, 360, 2
MAX_LABEL = 24  # the same limit as the name field on the Sensors page
FULL_SIZE_CHARS = 16  # longer lines get smaller text so they still fit, as on the page
MAX_FILE = 32768  # the largest picture the hub accepts
LINE_HEIGHT = 70
CRF = 38  # picture quality: higher is smaller. Large text stays sharp at this level, and every picture passes through the ESP32's RAM.
GREEN, RED, AMBER = '0x004000', '0xB00000', '0xB06000'
STATES = [('active', 'ACTIVE'), ('approaching', 'APPROACHING'), ('away', 'MOVING AWAY'), ('ltr', 'LEFT TO RIGHT'), ('rtl', 'RIGHT TO LEFT')]
FONTS = [('C:/Windows/Fonts/arial.ttf', r"C\:/Windows/Fonts/arial.ttf"),
         ('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')]


def font():
    for path, escaped in FONTS:
        if os.path.exists(path):
            return escaped
    sys.exit('no usable font found; add one to FONTS')


def nals(data):
    starts = [m.start() for m in re.finditer(b'\x00\x00\x01', data)]
    out = []
    for k, s in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(data)
        n = data[s + 3:end]
        out.append(n.rstrip(b'\x00') if k + 1 < len(starts) else n)
    return out


def text_filters(lines, workdir):
    filters = []
    top = (HEIGHT - LINE_HEIGHT * len(lines)) // 2 + 10
    for i, text in enumerate(lines):
        name = f'line{i}.txt'
        with open(os.path.join(workdir, name), 'w', encoding='utf8') as f:
            f.write(text)
        size = min(48, 48 * FULL_SIZE_CHARS // len(text))
        filters.append(f"drawtext=fontfile='{font()}':textfile={name}:fontcolor=white:fontsize={size}:x=(w-text_w)/2:y={top + LINE_HEIGHT * i}")
    return filters


def thumbnail(colour, lines, workdir):
    """Returns a small JPEG, for ONVIF clients that ask for a snapshot of a built-in picture."""
    out = os.path.join(workdir, 'frame.jpg')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', f'color=c={colour}:s={WIDTH}x{HEIGHT}:d=1:r=1',
                    '-vf', ','.join(text_filters(lines, workdir) + [f'scale={WIDTH // 2}:{HEIGHT // 2}']), '-frames:v', '1', '-q:v', '6', '-pix_fmt', 'yuvj420p', '-f', 'mjpeg', out],
                   check=True, cwd=workdir)
    with open(out, 'rb') as f:
        return f.read()


def write_snapshots():
    with tempfile.TemporaryDirectory() as tmp:
        images = [thumbnail(GREEN, ['ALL CLEAR'], tmp), thumbnail(RED, ['ALERT'], tmp)]
    lines = ['// Generated by tools/make_frames.py. Do not edit.', '#include "cam_frames.h"', '']
    for i, image in enumerate(images):
        lines.append(f"static const uint8_t s{i}[] = {{{','.join(str(x) for x in image)}}};")
    table = ', '.join(f'{{s{i}, {len(image)}}}' for i, image in enumerate(images))
    lines += ['', f'const CamJpeg CAM_SNAPSHOTS[] = {{{table}}};', '']
    with open(SNAPSHOTS, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines))
    print('built-in snapshots:', [len(image) for image in images], 'bytes')


def encode(colour, lines, workdir):
    """Returns [SPS, PPS, IDR]."""
    filters = text_filters(lines, workdir)
    out = os.path.join(workdir, 'frame.h264')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', f'color=c={colour}:s={WIDTH}x{HEIGHT}:d=1:r=1',
                    '-vf', ','.join(filters), '-frames:v', '1', '-c:v', 'libx264', '-profile:v', 'baseline', '-level', '3.0', '-crf', str(CRF),
                    '-pix_fmt', 'yuv420p', '-x264-params', 'scenecut=0:aud=0', '-f', 'h264', out],
                   check=True, cwd=workdir)
    with open(out, 'rb') as f:
        units = {n[0] & 31: n for n in nals(f.read())}
    if not all(t in units for t in (5, 7, 8)):
        sys.exit(f'frame for {lines!r} is missing SPS, PPS or IDR: {sorted(units)}')
    return [units[7], units[8], units[5]]


def annexb(units):
    return b''.join(b'\x00\x00\x00\x01' + n for n in units)


def sensor_files(label):
    """Returns {file name: bytes} for one sensor."""
    if not 0 < len(label) <= MAX_LABEL:
        sys.exit(f'label must be 1-{MAX_LABEL} characters: {label!r}')
    files = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, text in STATES:
            files[f'{key}.h264'] = annexb(encode(RED, [label, text], tmp))
            files[f'{key}-delayed.h264'] = annexb(encode(AMBER, [label, text, 'DELAYED'], tmp))
    for name, data in files.items():
        if len(data) > MAX_FILE:
            sys.exit(f'{label!r} {name} is {len(data)} bytes, more than the hub accepts ({MAX_FILE}); raise CRF')
    return files


def write_builtin():
    with tempfile.TemporaryDirectory() as tmp:
        frames = [encode(GREEN, ['ALL CLEAR'], tmp), encode(RED, ['ALERT'], tmp)]
    lines = ['// Generated by tools/make_frames.py. Do not edit.', '#include "cam_frames.h"', '']
    table = []
    for i, units in enumerate(frames):
        names = []
        for j, nal in enumerate(units):
            lines.append(f"static const uint8_t f{i}_{j}[] = {{{','.join(str(x) for x in nal)}}};")
            names.append(f'{{f{i}_{j}, {len(nal)}}}')
        lines.append(f'static const CamNal f{i}[] = {{{", ".join(names)}}};')
        table.append(f'{{f{i}, {len(units)}}}')
    lines += ['', f'const CamFrame CAM_FRAMES[] = {{{", ".join(table)}}};', f'const int CAM_WIDTH = {WIDTH};',
              f'const int CAM_HEIGHT = {HEIGHT};', f'const int CAM_FPS = {FPS};', '']
    with open(BUILTIN, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines))


def main():
    write_snapshots()
    if '--snapshots-only' in sys.argv:
        return
    with open(os.path.join(ROOT, 'sensors.json'), encoding='utf8') as f:
        sensors = json.load(f)['sensors']
    seen = set()
    for s in sensors:
        if not re.fullmatch(r'([0-9A-F]{2}-){5}[0-9A-F]{2}', s['mac']):
            sys.exit(f"MAC must look like AA-BB-CC-DD-EE-01: {s['mac']!r}")
        if not 1 <= s['input'] <= 255:
            sys.exit(f"input must be 1-255: {s['input']}")
        if (s['mac'], s['input']) in seen:
            sys.exit(f"{s['mac']} input {s['input']} is listed twice")
        seen.add((s['mac'], s['input']))

    write_builtin()
    shutil.rmtree(DATA, ignore_errors=True)
    total = 0
    for s in sensors:
        folder = os.path.join(DATA, s['mac'], str(s['input']))
        os.makedirs(folder)
        for name, data in sensor_files(s['label']).items():
            with open(os.path.join(folder, name), 'wb') as f:
                f.write(data)
            total += len(data)
    print(f'built-in pictures written; {len(sensors)} sensors, {total} bytes in data/')


if __name__ == '__main__':
    main()
