"""Generate the pre-encoded H.264 frames from sensors.json into lib/sensorcam/cam_frames_data.cpp.

The ESP32 has no video encoder, so it streams still frames made here. Frame 0 is "ALL CLEAR";
frame N is sensor N active. Run this again after editing sensors.json. Needs ffmpeg.
"""
import json, os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'lib', 'sensorcam', 'cam_frames_data.cpp')
WIDTH, HEIGHT, FPS = 640, 360, 2
MAX_LABEL = 16
FONTS = [('C:/Windows/Fonts/arial.ttf', r"C\:/Windows/Fonts/arial.ttf"),
         ('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')]


def font():
    for path, escaped in FONTS:
        if os.path.exists(path):
            return escaped
    sys.exit('no usable font found; add one to FONTS')


def nals(data):
    starts = [m.start() for m in re.finditer(b'\x00\x00\x01', data)]
    out = []
    for k, s in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(data)
        n = data[s + 3:end]
        out.append(n.rstrip(b'\x00') if k + 1 < len(starts) else n)
    return out


def encode(colour, text, workdir):
    with open(os.path.join(workdir, 'label.txt'), 'w', encoding='utf8') as f:
        f.write(text)
    vf = f"drawtext=fontfile='{font()}':textfile=label.txt:fontcolor=white:fontsize=48:x=(w-text_w)/2:y=(h-text_h)/2"
    out = os.path.join(workdir, 'frame.h264')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', f'color=c={colour}:s={WIDTH}x{HEIGHT}:d=1:r=1',
                    '-vf', vf, '-frames:v', '1', '-c:v', 'libx264', '-profile:v', 'baseline', '-level', '3.0',
                    '-pix_fmt', 'yuv420p', '-x264-params', 'scenecut=0:aud=0', '-f', 'h264', out],
                   check=True, cwd=workdir)
    data = open(out, 'rb').read()
    units = {n[0] & 31: n for n in nals(data)}
    if not all(t in units for t in (5, 7, 8)):
        sys.exit(f'frame for {text!r} is missing SPS, PPS or IDR: {sorted(units)}')
    return [units[7], units[8], units[5]]


def c_bytes(b):
    return ','.join(str(x) for x in b)


def main():
    with open(os.path.join(ROOT, 'sensors.json'), encoding='utf8') as f:
        sensors = json.load(f)['sensors']
    if [s['id'] for s in sensors] != list(range(1, len(sensors) + 1)):
        sys.exit('sensor ids must be 1, 2, 3, ... in order')
    for s in sensors:
        if not 0 < len(s['label']) <= MAX_LABEL:
            sys.exit(f"label must be 1-{MAX_LABEL} characters: {s['label']!r}")
    wanted = [('0x004000', 'ALL CLEAR')] + [('0xB00000', s['label'] + ' ACTIVE') for s in sensors]

    with tempfile.TemporaryDirectory() as tmp:
        frames = [encode(colour, text, tmp) for colour, text in wanted]

    lines = ['// Generated by tools/make_frames.py from sensors.json. Do not edit.', '#include "cam_frames.h"', '']
    table = []
    for i, units in enumerate(frames):
        names = []
        for j, nal in enumerate(units):
            lines.append(f'static const uint8_t f{i}_{j}[] = {{{c_bytes(nal)}}};')
            names.append(f'{{f{i}_{j}, {len(nal)}}}')
        lines.append(f'static const CamNal f{i}[] = {{{", ".join(names)}}};')
        table.append(f'{{f{i}, {len(units)}}}')
    lines += ['', f'const CamFrame CAM_FRAMES[] = {{{", ".join(table)}}};', f'const int CAM_FRAME_COUNT = {len(frames)};',
              f'const int CAM_SENSOR_COUNT = {len(sensors)};', f'const int CAM_WIDTH = {WIDTH};',
              f'const int CAM_HEIGHT = {HEIGHT};', f'const int CAM_FPS = {FPS};', '']
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(lines))
    sizes = [sum(len(n) for n in u) for u in frames]
    print(f'{len(frames)} frames, {min(sizes)}-{max(sizes)} bytes each, {sum(sizes)} bytes total')


if __name__ == '__main__':
    main()
